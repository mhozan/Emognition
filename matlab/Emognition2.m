function renable(varargin)  %Reset to default values
disp('Replays allowed.')
S=varargin{1,3};
if strcmp(S.ch(1).Enable,'on')
    disp('Replays disallowed.')
    S.ch(1).Enable='off';
    S.ch(1).Value=0;
    S.ch(1).BackgroundColor=S.bgtxtcolor2;
    S.fmenu.Children(3,1).Label='Enable Replays and Amp. Normalization';
elseif strcmp(S.ch(1).Enable,'off')
    disp('Replays allowed.')
    S.ch(1).Enable='on';
    S.ch(1).BackgroundColor=S.bgtxtcolor2;
    S.fmenu.Children(3,1).Label='Disable Replays and Amp. Normalization';
end

if strcmp(S.ch(9).Enable,'on')
    disp('Normalization disallowed.')
    S.ch(9).Enable='off';
    S.ch(9).Value=0;
    S.ch(9).BackgroundColor=S.bgtxtcolor1;
    S.fmenu.Children(3,1).Label='Enable Replays and Amp. Normalization';
elseif strcmp(S.ch(9).Enable,'off')
    disp('Normalization allowed.')
    S.ch(9).Enable='on';
    S.ch(9).BackgroundColor=S.bgtxtcolor1;
    S.fmenu.Children(3,1).Label='Disable Replays and Amp. Normalization';
end



function [xlsfile] = mat2xls_emognition(varargin)
% function for generating an excel report from the .mat file.
% i copied most of this from savestate.m which is responsible
% for saving xls and pdf and csv files.
% mohsen 8/2/2017
datetag = datestr(datetime('now'),'_yyyymmdd_HHMMSS');

% varargin{1,3}.exefolder
[FileName,PathName,~] = uigetfile(fullfile(varargin{1,3}.exefolder,'*.mat'),'Select the .MAT file generated by Emognition','MultiSelect','on'); %the input argument can be empty for a uigetfile to pop up and ask for it.
if PathName == 0;   return; end %return if the pop up window is closed/canceled
if ischar(FileName)
    FileName = {FileName};
end
matfile = fullfile(PathName,FileName);

Nfile = size(matfile,2) ;
selpath = uigetdir(PathName,'Select the directory for saving the Excel file(s)');


for n=1:Nfile
    
    
    S = load(matfile{1,n});
    xlsfile = fullfile(selpath,FileName{1,n}); [matfile(1:end-4),datetag,'.xlsx']; %the file name and path of the excel file; Excel file will be saved in the exact same location as the matfile, with the same name plus a time tag.
    xlsfile = [xlsfile(1:end-4),datetag,'.xlsx'];
    S.correct = S.keyspressed==S.audinfo.emoindsorted; %compares pressed keys and played sequence for the correct answers
    
    %% confusion matrix sheet
    writematrix(S.tabl.Data,...
        xlsfile,'Sheet','Confusion Matrix','Range','B2:F6');
    writecell(S.confuble.XTickLabel',...
        xlsfile,'Sheet','Confusion Matrix','Range','B1:F1');
    writecell(S.confuble.XTickLabel,...
        xlsfile,'Sheet','Confusion Matrix','Range','A2:A6');
    %% percentages sheet
    writematrix(S.percentabl.Data,...
        xlsfile,'Sheet','Percentages','Range','B2');
    writecell({'happy';'scared';'neutral';'sad';'angry';'female';'male';'Total'},...
        xlsfile,'Sheet','Percentages','Range','A2');
    writecell({'% Correct','Avg. Reaction(S)','Avg. Replays'},...
        xlsfile,'Sheet','Percentages','Range','B1');
    
    %% pressed keys sheet
    
    writecell(S.shuffledaudios,...
        xlsfile,'Sheet','Pressed Keys','Range','A2');
    writematrix(S.correct,...
        xlsfile,'Sheet','Pressed Keys','Range','B2');
    writematrix(S.audinfo.emoindsorted,...
        xlsfile,'Sheet','Pressed Keys','Range','C2');
    writematrix(S.keyspressed,...
        xlsfile,'Sheet','Pressed Keys','Range','D2');
    writecell({'1: Happy';'2: Scared'; '3: Neutral'; '4: Sad'; '5: Angry'},...
        xlsfile,'Sheet','Pressed Keys','Range','H2');
    writematrix(real(reactiontime(S.instants)),...
        xlsfile,'Sheet','Pressed Keys','Range','E2');
    writecell({'Audio filename','Correct Answer?','Played Sequence','Pressed Keys','Reaction Times(S)','Replays?'},...
        xlsfile,'Sheet','Pressed Keys','Range','A1:F1');
end
msgbox(['Excel restult(s) saved in: \n', selpath])


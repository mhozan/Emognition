    function []=closerr(varargin)
        %         figure, plot(timevec,genSIN)
        %         if ~isempty(S)
        % if ~exist('S')
        if isfield(S,'fh')
            set(S.fh,'visible','on')
        end
        if isfield(S,'sinobj')
            stop(S.sinobj)
        end
        if isfield(S,'fhcalibFFT')
%             delete(S.fhcalibFFT)
            set(S.fhcalibFFT,'visible','off')

        end
        
        if isfield(S,'fhcalib')
%             delete(S.fhcalib)
            set(S.fhcalib,'visible','off')
            return
        end
    end

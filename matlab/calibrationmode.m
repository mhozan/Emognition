    function []=getvals(varargin)
        %         S=varargin{1,3};
        actiondata=varargin{1,2};
        caller=actiondata.Source.Tag; %Which Browse... button called?
        
        if ~isempty(caller)
            switch caller(3)
                case '1'
                    %         set(S.ed(3),'string',input_directory)
                case '2' %play sine for how many seconds?
                    S.Endtime=str2double(get(S.edcalib(2),'string'));
                    
                    if isnan(S.Endtime)
                        S.Endtime=5;
                        
                    elseif S.Endtime<2
                        S.Endtime=2;
                    elseif S.Endtime>300
                        S.Endtime=300;
                    end
                    %         pause(1)
                    set(S.edcalib(2),'string',num2str(S.Endtime))
                case '3'
                    S.hannlength=str2double(get(S.edcalib(3),'string'));
                    %         pause(1)
                    if isnan(S.hannlength)
                        S.hannlength=100;
                        
                    elseif S.hannlength<5
                        S.hannlength=5;
                    elseif S.hannlength>5000
                        S.hannlength=5000;
                        %                 set(S.edcalib(3),'string',S.hannlength)
                    end
                    
                    set(S.edcalib(3),'string',num2str(S.hannlength))
                case '4'
                    
                otherwise
                    %do nothing
            end
        else
            disp('something''s not right, calibrationmode.m line302')
        end
%         timevec=(1:1/Fs:S.Endtime).';  %
        % S.rms.average=.05;
        % Fs
        set(S.edcalib(1),'string',num2str(S.rms.average))
        set(S.edcalib(2),'string',num2str(S.Endtime))
        genSIN=sqrt(2)*S.rms.average*sin(2*pi*1000*(1:1/Fsin:S.Endtime).');  %generated 1KHz sine wave
        % a1=rms(genSIN)
%         whann=hann(round(S.hannlength*Fsin/1000)); %'hann' requires Signal Processing Toolbox.
        Nhann = S.hannlength*Fsin/1000;
        whann = sin(pi*[0:Nhann-1]/(Nhann-1)).^2.';  %'hann' equivalent without Signal Processing Toolbox
        wl=floor(length(whann)/2);
        
        
        genSIN(1:wl)=whann(1:wl).*genSIN(1:wl);  %window the beginning
        genSIN(end-wl+1:end)=whann(end-wl+1:end).*genSIN(end-wl+1:end);  %window the ending
%         assignin('base','S',S);
        set(S.edcalib,'call',{@getvals,S})
    end


    function []=playcalib(varargin)
        %         S=varargin{1,3};
        switch varargin{1,2}.Source.Tag
            case 'play'                
                set(S.plpa(1),'enable','off')
                set(S.plpa(2),'enable','on')
                set(S.edcalib(2),'enable','off')
                set(S.edcalib(3),'enable','off')
                %         x=S.sinobj;
                S.sinobj=audioplayer(genSIN,Fsin);
                set(S.sinobj,'StopFcn',@enabler);
                playblocking(S.sinobj)                
            case 'pause'
                stop(S.sinobj)
                set(S.plpa(1),'enable','on')
                set(S.plpa(2),'enable','off')
                set(S.edcalib(2),'enable','on')
                set(S.edcalib(3),'enable','on')
            otherwise
                disp('why are we here?')
                %do nothing                
        end
        
        
        if isfield(S,'fhcalib') && isfield(S,'chfft')
%             assignin('base','S',S); %just to see the  properties in workspace
            if 0% get(S.chfft,'val')
                NFFT = 2^nextpow2(5*length(genSIN)); % Next power of 2 from length of y
                YF = fft(genSIN,NFFT)/length(genSIN);
                f = Fs/2*linspace(0,1,NFFT/2+1);
                S.fhcalibFFT=figure(406);
                set(S.fhcalibFFT,'units','pixels',...
                    'position',[0.55 0.3 .4 .4].*S.screen.posvec,...
                    'menubar','none',...'menubar','figure',...
                    'toolbar','figure',...'none',...
                    'name','Calibration Sine Wave',...
                    'numbertitle','off',...
                    'resize','on');
                subplot(2,1,1)
                plot((1:1/Fs:S.Endtime).',genSIN),title('Hann-Windowed Sine in time and frequency domain')
                xlabel('Time (S)')
                ylabel('Amplitude')
                grid on, grid minor
                subplot(2,1,2)   % Plot single-sided amplitude spectrum.
                plot(f,2*abs(YF(1:NFFT/2+1)))
                xlim([990,1010])
                yl=get(gca,'ylim');
                ylim([yl(1)-0.01,yl(2)])
                title('Single-Sided Amplitude Spectrum of The Calibration Sine Wave')
                xlabel('Frequency (Hz)')
                ylabel('Amplitude')
                grid on, grid minor
            end
        end
        
        
        %         play(S.sinobj)
        
        %         set(S.pobj,'StopFcn',{@enablebutton,S});
        
    end

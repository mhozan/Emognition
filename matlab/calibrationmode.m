    [y,Fs]=audioread([S.audir,'\',S.audiosshuffled{1,1}{1,i}]);
    if S.ch(9).Value %Loudness normalization
        S.normcoefs(i)=max(y);
        %         S.normcoefs(i)=rms(y);
        y=(1/S.normcoefs(i))*y;
    end
%     S.rms.recordings(i)=rms(y); %'rms' requires Signal Processing Toolbox.
    S.rms.recordings(i) = sqrt(nanmean(y.^2));
end
